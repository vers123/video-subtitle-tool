"""
视频字幕提取工具 - 配置文件

所有可配置参数集中管理，修改此文件即可调整程序行为。
"""

# ============================================================
# 路径配置
# ============================================================

# 视频输入文件夹（相对于项目根目录）
VIDEO_INPUT_DIR = "video"

# 字幕输出文件夹（相对于项目根目录，英文名）
SUBTITLE_OUTPUT_DIR = "subtitles"

# 临时文件目录（处理过程中的中间文件）
TEMP_DIR = "temp"

# 错误日志文件路径
ERROR_LOG_FILE = "error.log"

# ============================================================
# 视频格式配置
# ============================================================

# 支持的视频文件扩展名
SUPPORTED_VIDEO_EXTENSIONS = [".mp4", ".mkv", ".avi", ".mov"]

# ============================================================
# Whisper 语音转文字配置
# ============================================================

# Whisper 模型规格（程序会根据 GPU 自动选择）
# 可选值: "tiny", "base", "small", "medium", "large-v3"
# 显存 >= 6GB -> medium, 否则 -> small
WHISPER_MODEL_PREFERRED = "medium"
WHISPER_MODEL_FALLBACK = "small"
WHISPER_MODEL_VRAM_THRESHOLD = 6  # GB，低于此值使用 fallback 模型

# 目标语言（None 表示自动检测）
WHISPER_LANGUAGE = None

# 是否翻译为英文（False 表示不翻译，只输出原语言）
WHISPER_TRANSLATE = False

# 音频提取参数
AUDIO_SAMPLE_RATE = 16000  # 16kHz，Whisper 推荐采样率
AUDIO_CHANNELS = 1         # 单声道

# ============================================================
# OCR 硬字幕识别配置
# ============================================================

# 视频底部截取区域比例（从底部往上截取的画面比例）
# 例如 0.15 表示截取底部 15% 的画面区域
OCR_BOTTOM_REGION_RATIO = 0.15

# OCR 截帧间隔（秒），每隔多少秒截取一帧进行识别
OCR_FRAME_INTERVAL = 1.0

# OCR 识别语言（PaddleOCR 语言模型）
# "ch" 表示中文，"en" 表示英文
OCR_LANGUAGE = "ch"

# 相邻相同文本合并的阈值（秒）
# 如果两段识别结果相同且时间间隔小于此值，则合并
OCR_MERGE_THRESHOLD = 2.0

# ============================================================
# 字幕输出配置
# ============================================================

# 输出格式（目前只支持 SRT）
OUTPUT_FORMAT = "srt"

# SRT 文件编码
SRT_ENCODING = "utf-8"

# 字幕文件名后缀（按提取方式区分）
SUBTITLE_SUFFIX = {
    "embedded": "_embedded",  # 软字幕提取
    "ocr": "_ocr",            # OCR 硬字幕识别
    "whisper": "_whisper",    # 语音转文字
}

# ============================================================
# 运行配置
# ============================================================

# 是否在处理完成后清理临时音频文件
CLEANUP_TEMP_FILES = True

# 是否显示详细进度信息
VERBOSE_OUTPUT = True

# GPU 设备（-1 表示 CPU，0 表示第一个 GPU）
GPU_DEVICE = 0

# ============================================================
# 命令行参数默认值
# ============================================================

# 默认提取方式（None 表示使用混合策略自动回退）
# 可选值: None, "embedded", "ocr", "whisper"
DEFAULT_METHOD = None
